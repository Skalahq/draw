const missing = rows(["11111", "10001", "10001", "10001", "10001", "10001", "11111"]);

/** Glyph cells for a label. `y` is the vertical center so SVG and PNG share placement. */
export function textGlyphs(text: string, x: number, y: number, fontSize: number): GlyphRect[] {
  const cell = fontSize / 7;
  const top = y - fontSize / 2;
  const rects: GlyphRect[] = [];
  let cursor = x;
  for (const character of text) {
    const pattern = glyphs[character] ?? missing;
    for (let row = 0; row < pattern.length; row++) {
      const bits = pattern[row];
      for (let column = 0; column < 5; column++) {
        if ((bits & (1 << (4 - column))) === 0) continue;
        rects.push({ x: cursor + column * cell, y: top + row * cell, width: cell, height: cell });
      }
    }
    cursor += cell * 6;
  }
  return rects;
}
